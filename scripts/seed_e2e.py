#!/usr/bin/env python3
"""Build a demo database for the UI: migrations, demo users, and one synthetic client.

    python scripts/seed_e2e.py --url postgresql://.../reconcile_demo --out data/demo --fresh

Creates (or with --fresh, drops and recreates) the database, applies db/migrations,
loads db/seed/demo.sql, then adds "Delta Distributors": a REGULAR client generated by
tools/synth.py, assigned to staff.a@demo.test, with a client login delta@demo.test
(password demo123). August 2026 is preloaded: imported, matched, a few decisions taken
and the filing calendar filled, so the app has data the moment it opens. September's
purchase register and GSTR-2B are written to --out for a live upload (open the month
from the board first). --empty-month instead opens September with no data (used by the
browser tests). Prints a JSON summary.
"""
import argparse
import json
import sys
from pathlib import Path
from urllib.parse import urlsplit, urlunsplit

import psycopg

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from db.migrate import run_migrations  # noqa: E402
from tools.synth import generate  # noqa: E402

PERIOD = "092026"


def recreate(url):
    parts = urlsplit(url)
    name = parts.path.lstrip("/")
    admin = psycopg.connect(urlunsplit(parts._replace(path="/postgres")), autocommit=True)
    try:
        admin.execute("SELECT pg_terminate_backend(pid) FROM pg_stat_activity "
                      "WHERE datname = %s AND pid <> pg_backend_pid()", (name,))
        admin.execute(f'DROP DATABASE IF EXISTS "{name}"')
        admin.execute(f'CREATE DATABASE "{name}"')
    finally:
        admin.close()


def drop(url):
    parts = urlsplit(url)
    name = parts.path.lstrip("/")
    admin = psycopg.connect(urlunsplit(parts._replace(path="/postgres")), autocommit=True)
    try:
        admin.execute("SELECT pg_terminate_backend(pid) FROM pg_stat_activity "
                      "WHERE datname = %s AND pid <> pg_backend_pid()", (name,))
        admin.execute(f'DROP DATABASE IF EXISTS "{name}"')
    finally:
        admin.close()


def seed(url, out, docs=60, seed_value=7, history=False):
    """Seed the demo. With history=True, August 2026 is imported and matched (ready to
    review) and September is left for a live upload; otherwise September is opened empty."""
    run_migrations(url)
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    manifest = generate(clients=1, docs=docs, period=PERIOD, seed=seed_value, out=str(out))
    c = manifest[0]
    conn = psycopg.connect(url, autocommit=False)
    try:
        if conn.execute("SELECT count(*) FROM firm").fetchone()[0] == 0:
            conn.execute((ROOT / "db/seed/demo.sql").read_text().replace("BEGIN;", "")
                         .replace("COMMIT;", ""))
        firm = conn.execute("SELECT firm_id FROM firm ORDER BY firm_id LIMIT 1").fetchone()[0]
        existing = conn.execute("SELECT client_id FROM client WHERE pan = %s", (c["pan"],)).fetchone()
        if existing:  # already seeded: same seed gives the same client; keep its data
            row = conn.execute("SELECT period_id FROM return_period WHERE gstin = %s AND period = %s",
                               (c["gstin"], PERIOD)).fetchone()
            conn.rollback()
            return _summary(existing[0], c, row[0] if row else None, out)
        cid = conn.execute("INSERT INTO client(firm_id, name, pan) VALUES (%s, %s, %s) "
                           "RETURNING client_id", (firm, "Delta Distributors", c["pan"])).fetchone()[0]
        conn.execute("INSERT INTO gstin_reg(gstin, client_id, taxpayer_type, filing_freq, "
                     "state_code, reg_date) VALUES (%s, %s, %s, 'MONTHLY', %s, '2019-04-01')",
                     (c["gstin"], cid, c["taxpayer_type"], c["gstin"][:2]))
        conn.execute("INSERT INTO app_user(firm_id, client_id, email, role, password_hash) "
                     "VALUES (%s, %s, 'delta@demo.test', 'client', crypt('demo123', gen_salt('bf')))",
                     (firm, cid))
        conn.execute("INSERT INTO staff_assignment(user_id, client_id) SELECT user_id, %s "
                     "FROM app_user WHERE email = 'staff.a@demo.test'", (cid,))
        if history:
            _load_history(conn, c["gstin"], out / "august", docs, seed_value)
            pid = None
        else:
            pid = conn.execute("SELECT sp_open_period(%s, %s)", (c["gstin"], PERIOD)).fetchone()[0]
        conn.commit()
    finally:
        conn.close()
    return _summary(cid, c, pid, out)


HISTORY = "082026"


def _load_history(conn, gstin, folder, docs, seed_value):
    """August 2026, already through the pipeline: books and 2B imported, matched, a few
    decisions taken by staff A, supplier scores and the filing calendar filled in."""
    from api.uploads import BOOKS_COLUMNS, parse_books_csv
    m = generate(clients=1, docs=docs, period=HISTORY, seed=seed_value, out=str(folder))[0]
    assert m["gstin"] == gstin, "same seed must give the same client"
    staff = conn.execute("SELECT user_id FROM app_user WHERE email = 'staff.a@demo.test'").fetchone()[0]
    pid = conn.execute("SELECT sp_open_period(%s, %s)", (gstin, HISTORY)).fetchone()[0]

    cols = list(BOOKS_COLUMNS.values())
    for r in parse_books_csv((folder / m["books_file"]).read_text(encoding="utf-8-sig")):
        conn.execute(f"INSERT INTO books_staging(period_id, {', '.join(cols)}) "
                     f"VALUES (%s, {', '.join(['%s'] * len(cols))})", (pid, *(r[k] for k in cols)))
    conn.execute("SELECT sp_import_books(%s, %s)", (pid, staff))
    payload = (folder / m["gstr2b_file"]).read_text()
    imp = conn.execute("SELECT sp_import_gstr2b(%s, %s::jsonb, 'DRAFT_2B', %s)",
                       (pid, payload, staff)).fetchone()[0]
    conn.execute("SELECT sp_reconcile(%s, %s)", (imp, staff))
    conn.execute("SELECT sp_refresh_reviews(%s)", (imp,))
    conn.execute("SELECT sp_refresh_party_score()")

    # A few decisions, taken as staff A so maker-checker and thresholds apply as usual.
    picks = [("ONLY_IN_BOOKS", 2, "CHASE", "PENDING", "Asked supplier to upload in GSTR-1"),
             ("ONLY_IN_2B", 1, "INELIGIBLE", "REJECT", "Not our purchase"),
             ("MISMATCH", 1, "ACCEPT", "ACCEPT", "Difference is the supplier's freight charge")]
    conn.execute("SET LOCAL ROLE rc_staff")
    conn.execute("SELECT set_config('app.user_id', %s, true)", (str(staff),))
    for status, n, decision, ims, remark in picks:
        for (rid,) in conn.execute(
                "SELECT result_id FROM v_queue WHERE period_id = %s AND status::text = %s "
                "ORDER BY tax_at_risk DESC NULLS LAST LIMIT %s", (pid, status, n)).fetchall():
            conn.execute("SELECT sp_propose(%s, %s::review_decision, %s::ims_action, NULL, %s)",
                         (rid, decision, ims, remark))
    conn.execute("RESET ROLE")
    conn.execute("SELECT set_config('app.user_id', '', true)")
    conn.execute("SELECT sp_generate_filings(%s, '2026-04-01', '2026-10-31')", (gstin,))


def _summary(cid, c, pid, out):
    return {"client_id": cid, "gstin": c["gstin"], "period": PERIOD, "period_id": pid,
            "books": str(out / f"books_{c['gstin']}.csv"),
            "gstr2b": str(out / f"gstr2b_{c['gstin']}.json")}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--url", required=True)
    ap.add_argument("--out", default="data/demo")
    ap.add_argument("--docs", type=int, default=60)
    ap.add_argument("--fresh", action="store_true", help="drop and recreate the database")
    ap.add_argument("--empty-month", action="store_true",
                    help="open September empty instead of preloading a matched August (tests)")
    ap.add_argument("--drop", action="store_true", help="only drop the database, then exit")
    a = ap.parse_args(argv)
    if a.drop:
        drop(a.url)
        return 0
    if a.fresh:
        recreate(a.url)
    print(json.dumps(seed(a.url, a.out, a.docs, history=not a.empty_month)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
